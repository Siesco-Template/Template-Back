namespace ImportExportComponent.Dtos
{
    /// <summary>
    /// Represents a table column metadata for import/export operations
    /// </summary>
    public class TableColumnDto
    {
        /// <summary>
        /// Column name (property name)
        /// </summary>
        public string Name { get; set; } = string.Empty;

        /// <summary>
        /// Display name (can be used for UI display)
        /// </summary>
        public string DisplayName { get; set; } = string.Empty;

        /// <summary>
        /// Data type of the column
        /// </summary>
        public string DataType { get; set; } = string.Empty;

        /// <summary>
        /// Whether the column is required (not nullable)
        /// </summary>
        public bool IsRequired { get; set; }

        /// <summary>
        /// Maximum length for string columns
        /// </summary>
        public int? MaxLength { get; set; }

        /// <summary>
        /// Whether this column is a primary key
        /// </summary>
        public bool IsPrimaryKey { get; set; }

        /// <summary>
        /// Foreign table name if this is a foreign key column
        /// </summary>
        public string? ForeignTable { get; set; }

        /// <summary>
        /// Foreign column name if this is a foreign key column
        /// </summary>
        public string? ForeignColumn { get; set; }

        /// <summary>
        /// Whether this column is auto-generated (identity/auto-increment)
        /// </summary>
        public bool IsAutoGenerated { get; set; }
    }
}

